    try std.testing.expectEqualStrings(
        \\/* Generated by Nov. */
        \\#include <stdbool.h>
        \\#include <stdint.h>
        \\
        \\typedef bool (*nov_fn_2)(int32_t, int32_t);
        \\typedef int32_t (*nov_fn_3)(int32_t);
        \\typedef int32_t (*nov_fn_4)(nov_fn_3, int32_t);
        \\typedef int32_t (*nov_fn_5)(void);
